NO_KANA = re.compile(r"^[^ぁ-んァ-ヶ]*$")


def to_zh(ja):
    """回傳中文名稱;名稱本來就沒有日文假名(已經是中文/英文)就回傳 None,代表不用翻。"""
    if ja in OVERRIDES:
        return OVERRIDES[ja]
    if NO_KANA.match(ja):
        return None
    out = ja
    for src, dst in TERMS:
        out = out.replace(src, dst)
    out = re.sub(r"\s+", " ", out).strip()
    out = re.sub(r"\s*/\s*", "/", out)
    out = re.sub(r"\(\s+", "(", out)
    return out


def full_name(ja):
    zh = to_zh(ja)
    return ja if not zh else f"{ja} {zh}"
